  "def bar_weeks(first, last):\n    names = []\n    totals = []\n    for w in range(first, last + 1):\n        names.append(\"W\" + str(w))\n        totals.append(sum([p for ww, d, p in records if ww == w]))\n    plt.bar(names, totals)\n    return names, totals\n";
